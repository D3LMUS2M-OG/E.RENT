#!/usr/bin/env python3
"""Builds supabase/seed_geography.sql from the two shapefiles (no GIS libraries needed).
Usage: python3 scripts/build_geography.py <ke_subcounty_dir> <Kenya_Wards_dir>
Reads attribute tables (.dbf) and polygon centroids (.shp). Names are cleaned, centroids are approximate."""
import re, struct, sys, os, collections

def read_dbf(path):
    with open(path, 'rb') as f:
        h = f.read(32); n = struct.unpack('<I', h[4:8])[0]; hl, rl = struct.unpack('<HH', h[8:12]); fields = []
        while True:
            d = f.read(32)
            if d[0] == 0x0D: break
            fields.append((d[:11].split(b'\0')[0].decode(), d[16]))
        f.seek(hl); rows = []
        for _ in range(n):
            r = f.read(rl); o = 1; row = {}
            for nm, l in fields: row[nm] = r[o:o + l].decode('utf-8', 'replace').strip(); o += l
            rows.append(row)
    return rows

def centroids(path):
    out = []
    with open(path, 'rb') as f:
        f.seek(100)
        while True:
            h = f.read(8)
            if len(h) < 8: break
            _, clen = struct.unpack('>ii', h); body = f.read(clen * 2)
            nparts, npts = struct.unpack('<ii', body[36:44])
            parts = list(struct.unpack('<%di' % nparts, body[44:44 + 4 * nparts])) + [npts]; o = 44 + 4 * nparts
            pts = [struct.unpack('<dd', body[o + 16 * i:o + 16 * i + 16]) for i in range(npts)]
            A = cx = cy = 0.0
            for i in range(nparts):
                r = pts[parts[i]:parts[i + 1]]; a = x_ = y_ = 0.0
                for (x0, y0), (x1, y1) in zip(r, r[1:] + r[:1]):
                    c = x0 * y1 - x1 * y0; a += c; x_ += (x0 + x1) * c; y_ += (y0 + y1) * c
                a /= 2
                if a: cx += x_ / 6; cy += y_ / 6; A += a
            out.append((cx / A, cy / A) if A else (pts[0][0], pts[0][1]))
    return out

ROMAN = {'ii', 'iii', 'iv', 'vi', 'vii', 'viii', 'ix'}
def clean(name, strip):
    s = re.sub(r'\s+', ' ', name.replace('`', "'")).strip()
    s = re.sub(strip, '', s, flags=re.I).strip()
    if s.isupper(): s = s.lower()
    s = re.sub(r"(^|[\s\-/(])([a-z])", lambda m: m.group(1) + m.group(2).upper(), s)
    return ' '.join(w.upper() if w.lower() in ROMAN else w for w in s.split(' '))

slugify = lambda s: re.sub(r'-+', '-', re.sub(r'[^a-z0-9]+', '-', s.lower().replace("'", ''))).strip('-')
norm = lambda s: re.sub(r'[^a-z0-9]', '', s.lower())
q = lambda s: "'" + s.replace("'", "''") + "'"

def main(sub_dir, ward_dir):
    sc = read_dbf(os.path.join(sub_dir, 'ke_subcounty.dbf')); scc = centroids(os.path.join(sub_dir, 'ke_subcounty.shp'))
    wd = read_dbf(os.path.join(ward_dir, 'kenya_wards.dbf')); wdc = centroids(os.path.join(ward_dir, 'kenya_wards.shp'))
    subs = {}; used = collections.defaultdict(set)
    for r, (lng, lat) in zip(sc, scc):
        county = norm(r['county']); name = clean(r['subcounty'], r'\s*sub[\s-]*county\s*$')
        slug = slugify(name); i = 2
        while slug in used[county]: slug = f'{slugify(name)}-{i}'; i += 1
        used[county].add(slug)
        subs[(county, norm(name))] = dict(county=county, name=name, slug=slug, lat=lat, lng=lng, ext=r['dhis2_id'])
    wards = []; wused = collections.defaultdict(set)
    for r, (lng, lat) in zip(wd, wdc):
        key = (norm(r['county']), norm(clean(r['subcounty'], r'\s*sub[\s-]*county\s*$')))
        if key not in subs: raise SystemExit(f"ward {r['ward']} has no sub-county {key}")
        name = clean(r['ward'], r'\s*ward\s*$'); slug = slugify(name); i = 2
        while slug in wused[key]: slug = f'{slugify(name)}-{i}'; i += 1
        wused[key].add(slug)
        wards.append(dict(key=key, name=name, slug=slug, lat=lat, lng=lng, ext=r['uid'] or None))
    out = ['-- Generated by scripts/build_geography.py from the supplied shapefiles. Do not edit by hand.',
           f'-- {len(subs)} sub-counties, {len(wards)} wards. Centroids are approximate (polygon centre of mass).',
           'begin;', 'create temp table _sc (county text, name text, slug text, lat float8, lng float8, ext text) on commit drop;',
           'create temp table _wd (county text, sub_slug text, name text, slug text, lat float8, lng float8, ext text) on commit drop;']
    out.append('insert into _sc values')
    out.append(',\n'.join(f"({q(s['county'])},{q(s['name'])},{q(s['slug'])},{s['lat']:.5f},{s['lng']:.5f},{q(s['ext'])})" for s in subs.values()) + ';')
    out.append('insert into _wd values')
    out.append(',\n'.join(f"({q(w['key'][0])},{q(subs[w['key']]['slug'])},{q(w['name'])},{q(w['slug'])},{w['lat']:.5f},{w['lng']:.5f},{q(w['ext']) if w['ext'] else 'null'})" for w in wards) + ';')
    out.append("""
-- county names are matched ignoring case, spaces and punctuation
insert into public.sub_counties (county_id, name, slug, lat, lng, external_id)
select c.id, s.name, s.slug, s.lat, s.lng, s.ext from _sc s
join public.counties c on regexp_replace(lower(c.name), '[^a-z0-9]', '', 'g') = s.county
on conflict (county_id, slug) do update set name = excluded.name, lat = excluded.lat, lng = excluded.lng, external_id = excluded.external_id;

insert into public.wards (sub_county_id, name, slug, lat, lng, external_id)
select sc.id, w.name, w.slug, w.lat, w.lng, w.ext from _wd w
join public.counties c on regexp_replace(lower(c.name), '[^a-z0-9]', '', 'g') = w.county
join public.sub_counties sc on sc.county_id = c.id and sc.slug = w.sub_slug
on conflict (sub_county_id, slug) do update set name = excluded.name, lat = excluded.lat, lng = excluded.lng, external_id = excluded.external_id;

do $$ declare s int; w int; begin
  select count(*) into s from public.sub_counties; select count(*) into w from public.wards;
  raise notice 'sub_counties: %, wards: %', s, w;
end $$;
commit;""")
    open('supabase/seed_geography.sql', 'w').write('\n'.join(out) + '\n')
    print(len(subs), 'sub-counties,', len(wards), 'wards')
    for k in list(subs)[:3]: print(subs[k]['name'], subs[k]['slug'])
    print([w['name'] for w in wards[:6]])
    odd = [w['name'] for w in wards if re.search(r'[^A-Za-z0-9 \-\'/().&,]', w['name']) or w['name'] != w['name'].strip()]
    print('names with unusual characters:', odd[:15])

main(sys.argv[1], sys.argv[2])
